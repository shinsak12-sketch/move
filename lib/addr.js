// 조직 주소 정리 — 층 · 호수 · 건물명을 떼고 "도로명 + 건물번호" 또는 "동 + 번지"까지만 남김
// 같은 건물(층만 다른 경우 포함)은 같은 키가 되어 좌표 · 거리를 한 번만 계산함
const SIDO = [
  [/^서울(특별시|시)?$/, '서울특별시'], [/^부산(광역시|시)?$/, '부산광역시'], [/^대구(광역시|시)?$/, '대구광역시'],
  [/^인천(광역시|시)?$/, '인천광역시'], [/^광주(광역시)?$/, '광주광역시'], [/^대전(광역시|시)?$/, '대전광역시'],
  [/^울산(광역시|시)?$/, '울산광역시'], [/^세종(특별자치시|시)?$/, '세종특별자치시'], [/^경기(도)?$/, '경기도'],
  [/^강원(도|특별자치도)?$/, '강원특별자치도'], [/^충북$|^충청북도$/, '충청북도'], [/^충남$|^충청남도$/, '충청남도'],
  [/^전북$|^전라북도$|^전북특별자치도$/, '전북특별자치도'], [/^전남$|^전라남도$/, '전라남도'],
  [/^경북$|^경상북도$/, '경상북도'], [/^경남$|^경상남도$/, '경상남도'], [/^제주(도|특별자치도)?$/, '제주특별자치도']
];
// '광주'는 경기도 광주시도 있어서 첫 단어일 때만 광역시로 봄

export function baseAddr(raw) {
  let s = String(raw || '').replace(/[,，]/g, ' ').replace(/\s+/g, ' ').trim();
  const parts = s.split(' ');
  for (const [re, to] of SIDO) if (re.test(parts[0])) { parts[0] = to; break; }
  s = parts.join(' ');
  // 도로명: ○○로 12, ○○로 12-3, ○○로12번길 34, ○○로 69길 21
  const road = s.match(/^(.*?(?:로|길)(?:\s*\d+(?:번)?길)?\s*\d+(?:-\d+)?)(?![\d-])/);
  // 지번: ○○동 123-4, ○○동2가 210-1, ○○리 56 (번지 제거)
  const jibun = s.match(/^(.*?(?:동\d+가|[동리가])\s*\d+(?:-\d+)?)(?![\d-])/);
  let base = road ? road[1] : jibun ? jibun[1] : s;
  // 도로명 앞에 '○○로'가 시군구 이름 안에 걸린 경우를 피함: 시도 바로 뒤에서 끝나면 버림
  if (base.split(' ').length < 3 && jibun) base = jibun[1];
  base = base.replace(/\s+/g, ' ').trim();
  return { base, key: base.replace(/\s+/g, '') };
}
